import fs from 'node:fs';
import path from 'node:path';

const services = [
  'auth-service',
  'product-service',
  'order-service',
  'inventory-service',
  'customer-service',
  'content-service',
];

for (const s of services) {
  const lockFile = path.resolve('services', s, 'prisma', 'migrations', 'migration_lock.toml');
  fs.writeFileSync(lockFile, '# Please do not edit this file manually\nprovider = "mysql"\n', 'utf-8');
  console.log(`Added migration_lock.toml for ${s}`);
}
